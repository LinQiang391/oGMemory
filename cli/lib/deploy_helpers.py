"""Docker deployment helpers for ogmem onboard."""

from __future__ import annotations

import logging
import os
import shlex
import subprocess
from pathlib import Path

from cli.lib.config_loader import get_project_root

logger = logging.getLogger(__name__)


def generate_deploy_env(
    llm_config: dict,
    db_config: dict | None = None,
    container_config: dict | None = None,
    output_path: Path | None = None,
) -> Path:
    """Generate a deploy.env file from onboarding parameters."""
    root = get_project_root()
    output_path = output_path or root / "deploy" / "deploy.env"

    lines = [
        "# Generated by ogmem onboard",
        "",
        "LLM_PROVIDER=\"{}\"".format(llm_config["provider"]),
        "LLM_API_KEY=\"{}\"".format(llm_config.get("api_key", "")),
        "LLM_BASE_URL=\"{}\"".format(llm_config.get("base_url", "")),
        "LLM_MODEL=\"{}\"".format(llm_config.get("model", "")),
    ]

    if db_config:
        og_enabled = db_config.get("enable_opengauss", True)
        lines.append("")
        lines.append("ENABLE_OPENGAUSS=\"{}\"".format("true" if og_enabled else "false"))
        if og_enabled:
            lines.append("OG_HOST_PORT=\"{}\"".format(db_config.get("port", "15432")))
        lines.append("OPENGAUSS_HOST_IP=\"{}\"".format(db_config.get("host_ip", "127.0.0.1")))

    if container_config:
        lines.append("")
        lines.append("OPENCLAW_HOST_IP=\"{}\"".format(container_config.get("host_ip", "127.0.0.1")))
        if container_config.get("container_name"):
            lines.append("OGMEM_CONTAINER_NAME=\"{}\"".format(container_config["container_name"]))
        if container_config.get("openclaw_container_name"):
            lines.append("OPENCLAW_CONTAINER_NAME=\"{}\"".format(container_config["openclaw_container_name"]))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output_path


def generate_quickstart_env(
    llm_config: dict,
    embedding_config: dict,
    *,
    instance_name: str = "ogmem",
    opengauss_port: int = 15432,
    ogmem_http_port: int = 18090,
    ogmem_mcp_port: int = 18091,
    openclaw_ce_port: int = 18790,
    openclaw_mcp_port: int = 18791,
    output_path: Path,
) -> Path:
    """Generate the environment file consumed by deploy/user-quickstart."""

    values = {
        "INSTANCE_NAME": instance_name,
        "OPENGAUSS_HOST_PORT": opengauss_port,
        "OGMEM_HTTP_HOST_PORT": ogmem_http_port,
        "OGMEM_MCP_HOST_PORT": ogmem_mcp_port,
        "OPENCLAW_CE_HOST_PORT": openclaw_ce_port,
        "OPENCLAW_MCP_HOST_PORT": openclaw_mcp_port,
        "LLM_BASE_URL": llm_config.get("base_url", ""),
        "LLM_MODEL": llm_config.get("model", ""),
        "LLM_API_KEY": llm_config.get("api_key", ""),
        "EMBEDDING_PROVIDER": embedding_config.get("provider", "openai"),
        "EMBEDDING_BASE_URL": embedding_config.get("base_url", ""),
        "EMBEDDING_MODEL": embedding_config.get("model", ""),
        "EMBEDDING_API_KEY": embedding_config.get("api_key", ""),
        "EMBEDDING_DIMENSION": embedding_config.get("dimension", 1024),
    }
    lines = [
        "# Generated by ogmem onboard; consumed by deploy/user-quickstart/deploy.sh",
        *[f"export {name}={shlex.quote(str(value))}" for name, value in values.items()],
        "",
        "# Re-running Docker onboard recreates containers but preserves these directories.",
        "# Set RESET_* explicitly only when the corresponding data can be discarded.",
        "export RESET_OPENCLAW_CONFIG='false'",
        "export RESET_AGFS_DATA='false'",
        "export RESET_OPENGAUSS_DATA='false'",
    ]
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output_path


