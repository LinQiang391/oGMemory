"""Lifecycle aging job for memory nodes.

Evaluates memory nodes for lifecycle actions based on age and usage patterns.
Supports automatic archival and deletion of stale content.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone, timedelta
from logging import getLogger
from typing import Any

from core.interfaces import ContextFS
from core.models import ContextNode, RequestContext
from core.uri_resolver import URIResolver
from extraction.schemas.registry import SchemaRegistry


logger = getLogger(__name__)


@dataclass
class AgingProposal:
    """A proposal for lifecycle action on a memory node.

    Proposals are generated by AgingJob.scan() and executed by
    AgingJob.execute() when auto_approved=True.
    """
    uri: str
    action: str  # "archive", "merge", "delete"
    reason: str
    details: dict[str, Any] = field(default_factory=dict)
    created_at: str = ""
    auto_approved: bool = False

    def __post_init__(self):
        if not self.created_at:
            self.created_at = datetime.now(timezone.utc).isoformat()


class AgingJob:
    """Evaluates and executes lifecycle actions on memory nodes.

    Scans all enabled memory types and generates proposals for:
    - Archiving: Active nodes with no recent hits (stale but valuable)
    - Deletion: Archived nodes beyond retention threshold

    Constructor Args:
        fs: ContextFS implementation for node access
        registry: SchemaRegistry for memory type schemas
        ctx: RequestContext for access control
        archive_threshold_days: Days of inactivity before archival (default 90)
        delete_threshold_days: Days since archival before deletion (default 365)
        similarity_threshold: Minimum similarity for merge proposals (default 0.85)
        auto_approve: If True, all proposals are auto-approved (default False)
    """

    def __init__(
        self,
        fs: ContextFS,
        registry: SchemaRegistry,
        ctx: RequestContext,
        *,
        archive_threshold_days: int = 90,
        delete_threshold_days: int = 365,
        similarity_threshold: float = 0.85,
        auto_approve: bool = False,
    ):
        """Initialize the AgingJob.

        Args:
            fs: ContextFS implementation
            registry: SchemaRegistry for schema access
            ctx: RequestContext for authorization
            archive_threshold_days: Days of inactivity before archival
            delete_threshold_days: Days in archive before deletion
            similarity_threshold: Similarity threshold for merge proposals
            auto_approve: Automatically approve all proposals
        """
        self._fs = fs
        self._registry = registry
        self._ctx = ctx
        self._archive_threshold = timedelta(days=archive_threshold_days)
        self._delete_threshold = timedelta(days=delete_threshold_days)
        self._similarity_threshold = similarity_threshold
        self._auto_approve = auto_approve
        self._resolver = URIResolver(registry)

    def scan(self) -> list[AgingProposal]:
        """Scan all enabled memory types and generate lifecycle proposals.

        Iterates through all enabled schemas, lists nodes in each directory,
        evaluates each node for lifecycle action based on age and usage.

        Returns:
            List of AgingProposal objects for nodes requiring action
        """
        proposals: list[AgingProposal] = []
        now = datetime.now(timezone.utc)

        for schema in self._registry.list_enabled():
            try:
                directory_uri = self._get_directory_uri(schema.memory_type)

                try:
                    child_uris = self._fs.list_children(directory_uri, self._ctx)
                except Exception as e:
                    logger.warning(f"Failed to list children for {directory_uri}: {e}")
                    continue

                for uri in child_uris:
                    try:
                        node = self._fs.read_node(uri, self._ctx)
                        proposal = self._evaluate_node(node, now)
                        if proposal:
                            proposals.append(proposal)
                    except Exception as e:
                        logger.warning(f"Failed to evaluate node {uri}: {e}")
                        continue

            except Exception as e:
                logger.error(f"Failed to process schema {schema.memory_type}: {e}")
                continue

        logger.info(f"AgingJob.scan generated {len(proposals)} proposals")
        return proposals

    def execute(self, proposals: list[AgingProposal]) -> dict[str, int]:
        """Execute lifecycle proposals.

        Only executes proposals where auto_approved=True.
        For "archive" actions, calls fs.archive_node(uri, ctx).
        For "delete" actions, calls fs.delete_node(uri, ctx).

        Args:
            proposals: List of AgingProposal objects to execute

        Returns:
            Stats dict with counts: {"archived": N, "deleted": N, "skipped": N, "errors": N}
        """
        stats = {"archived": 0, "deleted": 0, "skipped": 0, "errors": 0}

        for proposal in proposals:
            if not proposal.auto_approved:
                stats["skipped"] += 1
                continue

            try:
                if proposal.action == "archive":
                    self._execute_archive(proposal)
                    stats["archived"] += 1
                elif proposal.action == "delete":
                    self._fs.delete_node(proposal.uri, self._ctx)
                    stats["deleted"] += 1
                else:
                    logger.warning(f"Unknown action: {proposal.action}")
                    stats["skipped"] += 1

            except Exception as e:
                logger.error(f"Failed to execute {proposal.action} on {proposal.uri}: {e}")
                stats["errors"] += 1

        logger.info(f"AgingJob.execute results: {stats}")
        return stats

    def _evaluate_node(self, node: ContextNode, now: datetime) -> AgingProposal | None:
        """Evaluate a node for lifecycle action.

        Decision logic:
        - If status is ARCHIVED and age > delete_threshold → propose delete
        - If status is ACTIVE and hit_count_30d == 0 and age > archive_threshold → propose archive
        - Otherwise skip node (recent hits or too young)

        Args:
            node: ContextNode to evaluate
            now: Current datetime for age calculations

        Returns:
            AgingProposal if action needed, None otherwise
        """
        metadata = node.metadata
        status = metadata.get("status", "ACTIVE")
        age = self._estimate_age(metadata, now)

        if status == "ARCHIVED":
            if age > self._delete_threshold:
                return AgingProposal(
                    uri=node.uri,
                    action="delete",
                    reason=f"Archived for {age.days} days (threshold: {self._delete_threshold.days})",
                    details={"age_days": age.days, "status": status},
                    auto_approved=self._auto_approve,
                )
        elif status == "ACTIVE":
            hit_count_30d = metadata.get("hit_count_30d", 0)
            if hit_count_30d == 0 and age > self._archive_threshold:
                return AgingProposal(
                    uri=node.uri,
                    action="archive",
                    reason=f"No hits in 30 days, age {age.days} days (threshold: {self._archive_threshold.days})",
                    details={"age_days": age.days, "hit_count_30d": hit_count_30d},
                    auto_approved=self._auto_approve,
                )

        return None

    def _execute_archive(self, proposal: AgingProposal) -> None:
        """Execute archive action on a proposal.

        Calls fs.archive_node(uri, ctx) if available.
        Gracefully handles implementations where archive_node is not yet available.

        Args:
            proposal: AgingProposal with action="archive"
        """
        if hasattr(self._fs, "archive_node"):
            self._fs.archive_node(proposal.uri, self._ctx)
        else:
            logger.warning(f"archive_node not available on ContextFS, skipping {proposal.uri}")

    def _get_directory_uri(self, memory_type: str) -> str:
        """Get directory URI for a memory type.

        Uses URIResolver to render the directory template.

        Args:
            memory_type: Memory type identifier

        Returns:
            Directory URI string
        """
        return self._resolver.get_directory_uri(memory_type, self._ctx)

    def _estimate_age(self, metadata: dict[str, Any], now: datetime) -> timedelta:
        """Estimate node age from metadata timestamps.

        Tries to parse created_at, then updated_at, then falls back to epoch.

        Args:
            metadata: Node metadata dict
            now: Current datetime for calculation

        Returns:
            timedelta since node creation/update
        """
        timestamp_str = metadata.get("created_at") or metadata.get("updated_at")

        if timestamp_str:
            try:
                if isinstance(timestamp_str, str):
                    timestamp = datetime.fromisoformat(timestamp_str.replace("Z", "+00:00"))
                    if timestamp.tzinfo is None:
                        timestamp = timestamp.replace(tzinfo=timezone.utc)
                    return now - timestamp
            except Exception as e:
                logger.warning(f"Failed to parse timestamp {timestamp_str}: {e}")

        return timedelta(days=0)
